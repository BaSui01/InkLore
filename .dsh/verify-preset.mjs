import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
const app = path.resolve(process.argv[2] || 'D:/Dev/DSH Desktop/resources/app');
const dshHome = process.env.DSH_HOME;
if (!dshHome) throw new Error('DSH_HOME is required');
const requireApp = createRequire(path.join(app, 'package.json'));
const loadPackage = name => import(pathToFileURL(path.join(app, 'node_modules/@deepseek-ai', name, 'lib/index.js')).href);
const { scanRoot } = await loadPackage('dsh-agent-presets');
const { entryListSchema } = await loadPackage('cordis-plugin-include');
const { Config } = await loadPackage('dsh-tool-subagent');
const yaml = requireApp('js-yaml');
const root = path.join(dshHome, '.agent-presets');
const id = 'inklore-parallel-terra';
const found = (await scanRoot({ path: root, trust: 'user' }, pathToFileURL(app + path.sep).href)).find(p => p.id === id);
if (!found || found.broken) throw new Error(found?.broken || 'Preset not discovered');
const source = fs.readFileSync(new URL('./presets/inklore-parallel-terra/agent.cordis.yml', import.meta.url), 'utf8');
if (source !== fs.readFileSync(found.path, 'utf8')) throw new Error('Installed preset differs from project source');
const rows = yaml.load(source, { schema: entryListSchema });
const flatten = values => values.flatMap(row => row.disabled === true ? [] : row.group ? flatten(row.config) : [row]);
const tools = flatten(rows).filter(row => row.name === '@deepseek-ai/dsh-tool-subagent');
const names = new Set();
for (const row of tools) {
 const c = Config(row.config);
 if (names.has(c.toolName)) throw new Error('Duplicate tool ' + c.toolName);
 names.add(c.toolName);
 if (c.agentOptions?.provider !== 'basui' || c.agentOptions?.model !== 'gpt-5.6-terra' || c.agentOptions?.reasoningEffort !== 'high') throw new Error('Wrong model route ' + c.toolName);
 if (c.maxDepth !== 1 || c.backgroundMode !== 'continuable' || c.modelSelectionSettings) throw new Error('Unexpected delegation policy ' + c.toolName);
}
if (names.size !== 13) throw new Error('Expected 13 delegation tools');
const review = tools.find(row => row.config.toolName === 'subagent_review');
const expected = ['glob', 'grep', 'read', 'read_image', 'send_message'];
if (JSON.stringify([...review.config.toolFilter.allow].sort()) !== JSON.stringify(expected)) throw new Error('Reviewer must have read-only tools');
const settings = yaml.load(fs.readFileSync(path.join(dshHome, 'settings.yaml'), 'utf8'));
const provider = Object.values(settings).find(section => section?.providers?.basui)?.providers.basui;
const model = provider?.models?.find(value => value.id === 'gpt-5.6-terra');
if (!model || model.reasoningEfforts?.high !== 'high') throw new Error('Configured provider/model/high effort not found');
console.log(JSON.stringify({ status: 'pass', id, name: found.name, discovery: 'DSH scanRoot', delegationTools: [...names], provider: 'basui', model: model.id, reasoningEffort: 'high', maxDepth: 1, coordinationLimit: 4, hardConcurrencyLimit: false, sourceMatchesInstalled: true, liveModelRequest: 'not performed' }, null, 2));

// R1 design compiler. Source: api domain fragments; outputs are deterministic generated views.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const api = path.join(root, 'api');
const read = f => JSON.parse(fs.readFileSync(f, 'utf8'));
const json = value => JSON.stringify(value, null, 1) + '\n';
const write = (file, text) => { fs.mkdirSync(path.dirname(file), {recursive:true}); fs.writeFileSync(file,text); };
const escapePointer = s => s.split('~').join('~0').split('/').join('~1');
const methods = new Set(['get','post','put','patch','delete','head','options']);
const excluded = new Set(['openapi.json','error-catalog.json']);
const sources = fs.readdirSync(api).filter(f=>f.endsWith('.json')&&!excluded.has(f)).sort();
const paths = {}, origins = {}, operations = [], issues = [];
function rebase(node, source) {
 if(Array.isArray(node)) return node.map(n=>rebase(n,source));
 if(!node||typeof node!=='object') return node;
 const out={};
 for(const [k,v] of Object.entries(node)) {
  if(k==='$ref'&&typeof v==='string'&&!/^https?:/.test(v)) {
   const [file,frag=''] = v.split('#');
   const target=file?path.resolve(path.dirname(source),file):source;
   out[k]=path.relative(path.join(api,'generated'),target).split(path.sep).join('/')+'#'+frag;
  } else out[k]=rebase(v,source);
 }
 return out;
}
for(const file of sources) {
 const full=path.join(api,file), doc=read(full);
 for(const [route,item] of Object.entries(doc.paths||{})) {
  paths[route] ||= {}; origins[route] ||= {};
  for(const [method,operation] of Object.entries(item)) {
   if(methods.has(method)) {
    if(paths[route][method]) issues.push('Duplicate operation '+method+' '+route);
    paths[route][method]=rebase(operation,full); origins[route][method]=file;
    operations.push({route,method,file,operation});
   } else if(!paths[route][method]) paths[route][method]=rebase(operation,full);
  }
 }
}
if(issues.length) { console.error(issues.join('\n')); process.exit(1); }
const generated=path.join(api,'generated');
fs.mkdirSync(generated,{recursive:true});
for(const f of fs.readdirSync(generated)) if(/^paths-[a-z]+-[0-9]+[.]json$/.test(f)) fs.unlinkSync(path.join(generated,f));
const groups={};
for(const route of Object.keys(paths).sort()) { const g=route.split('/')[2]||'platform'; (groups[g]||=[]).push(route); }
const entry={openapi:'3.1.0',info:{title:'InkLore R1 Reconstruction API',version:'1.0.0-design',description:'Frozen design, not implementation evidence. Generated by tools/build-contracts.cjs.'},servers:[{url:'http://localhost:8080'}],security:[{BearerAuth:[]}],paths:{},components:{securitySchemes:read(path.join(api,'common.json')).components.securitySchemes}};
let shards=0;
for(const [group,routes] of Object.entries(groups)) {
 let chunk={}, index=1;
 function flush() {
  if(!Object.keys(chunk).length)return;
  const file='paths-'+group+'-'+String(index++).padStart(2,'0')+'.json';
  write(path.join(generated,file),json({'x-generated':'build-contracts.cjs',paths:chunk}));
  for(const route of Object.keys(chunk))entry.paths[route]={'$ref':'./generated/'+file+'#/paths/'+escapePointer(route)};
  chunk={}; shards++;
 }
 for(const route of routes) {
  if(Buffer.byteLength(json({paths:{[route]:paths[route]}}))>49000)throw Error('Single path too large: '+route);
  if(Buffer.byteLength(json({paths:{...chunk,[route]:paths[route]}}))>48000)flush();
  chunk[route]=paths[route];
 }
 flush();
}
write(path.join(api,'openapi.json'),json(entry));
const common=[
 ['platform.validation_failed',400,'fix_input'],['auth.unauthenticated',401,'reauthenticate'],['auth.forbidden',403,'none'],['platform.resource_not_found',404,'none'],['platform.method_not_allowed',405,'fix_input'],['platform.idempotency_conflict',409,'fix_input'],['platform.operation_in_progress',409,'read_status'],['platform.cursor_invalid',400,'fix_input'],['platform.request_too_large',413,'fix_input'],['platform.internal_error',500,'read_status'],['platform.dependency_unavailable',503,'retry_later'],['agent.event_cursor_expired',410,'read_status'],['agent.event_cursor_invalid',400,'fix_input'],['agent.execution_outcome_unknown',409,'read_status'],['platform.range_invalid',416,'fix_input']
].map(([code,http_status,recovery])=>({code,http_status,recovery,message_key:'errors.'+code,operations:['global']}));
const byCode=new Map(common.map(e=>[e.code,e]));
for(const {operation}of operations)for(const e of operation['x-errors']||[]) {
 if(typeof e!=='object'||!e.code||!Number.isInteger(e.http_status)) throw Error('Malformed x-errors '+operation.operationId);
 const known=byCode.get(e.code);
 if(known){if(known.http_status!==e.http_status)issues.push('Error HTTP conflict '+e.code+': '+known.http_status+'/'+e.http_status);if(!known.operations.includes(operation.operationId))known.operations.push(operation.operationId);}
 else byCode.set(e.code,{...e,message_key:'errors.'+e.code,operations:[operation.operationId]});
}
const errorGroups={};
for(const e of [...byCode.values()].sort((a,b)=>a.code.localeCompare(b.code)))(errorGroups[e.code.split('.')[0]]||=[]).push(e);

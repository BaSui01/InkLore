for(let i=1;i<=25;i++){const fr='FR-'+String(i).padStart(2,'0');const ids=operations.filter(x=>(x.operation['x-use-case']||'').includes(fr)).map(x=>x.operation.operationId).sort();trace.push('| '+fr+' | '+(ids.join(', ')||'UI控制器验收见15/17/20')+' |');}
write(path.join(root,'implementation','requirements-map.md'),trace.join('\n')+'\n');
